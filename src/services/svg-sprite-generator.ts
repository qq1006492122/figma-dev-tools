/**
 * SVG Sprite 生成器 - SVG Sprite Generator
 *
 * 核心职责：将多个 SVG 文件合并为一个 SVG Sprite（symbol 集合），
 * 支持通过 <use href="#icon-name"> 方式引用，适合图标库场景。
 *
 * @module
 */

import * as fs from 'node:fs';
import * as path from 'node:path';

import { optimize as svgoOptimize } from 'svgo';

/**
 * SVG Sprite 生成器配置
 */
export interface SpriteOptions {
  /** 输出文件路径（绝对路径） */
  outputPath: string;
  /** Sprite 中 symbol 的 id 前缀，默认 'icon-' */
  prefix?: string;
  /** 是否移除 SVG 中的 fill 属性（方便通过 CSS color 控制颜色），默认 true */
  removeFill?: boolean;
}

/**
 * 单个 SVG 的处理结果
 */
export interface SpriteResult {
  /** 图标名称（即 symbol id） */
  name: string;
  /** 是否处理成功 */
  success: boolean;
  /** 错误信息（失败时） */
  error?: string;
}

/**
 * 从已下载的 SVG 文件生成 SVG Sprite
 *
 * @param svgFiles - SVG 文件路径数组（绝对路径）
 * @param options - Sprite 生成配置
 * @returns 处理结果数组
 */
export function generateSvgSprite(svgFiles: string[], options: SpriteOptions): SpriteResult[] {
  const { outputPath, prefix = 'icon-', removeFill = true } = options;
  const results: SpriteResult[] = [];
  const symbols: string[] = [];

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });

  for (const filePath of svgFiles) {
    const fileName = path.basename(filePath, '.svg');
    const symbolId = `${prefix}${fileName}`;

    try {
      const svgContent = fs.readFileSync(filePath, 'utf-8');

      const viewBoxMatch = svgContent.match(/viewBox=["']([^"']+)["']/i);
      const viewBox = viewBoxMatch && viewBoxMatch[1] ? viewBoxMatch[1] : '0 0 24 24';

      const optimized = svgoOptimize(svgContent, {
        multipass: true,
        plugins: [
          'preset-default',
          'removeDimensions',
          {
            name: 'removeAttrs',
            params: {
              attrs: ['data-name', 'id'],
            },
          },
        ],
      });

      const innerMatch = optimized.data.match(/<svg[^>]*>([\s\S]*?)<\/svg>/i);
      let innerContent = innerMatch && innerMatch[1] ? innerMatch[1].trim() : optimized.data;

      if (removeFill) {
        innerContent = innerContent.replace(/\sfill="[^"]*"/gi, '');
        innerContent = innerContent.replace(/\sfill='[^']*'/gi, '');
      }

      symbols.push(`  <symbol id="${symbolId}" viewBox="${viewBox}">\n    ${innerContent}\n  </symbol>`);
      results.push({ name: symbolId, success: true });
    } catch (err) {
      results.push({
        name: fileName,
        success: false,
        error: err instanceof Error ? err.message : String(err),
      });
    }
  }

  const spriteContent = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Auto-generated by figma-dev-tools - SVG Sprite -->',
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">`,
    ...symbols,
    '</svg>',
    '',
  ].join('\n');

  fs.writeFileSync(outputPath, spriteContent, 'utf-8');

  return results;
}

/**
 * 生成 TypeScript 类型定义文件（图标名称联合类型 + 示例组件）
 *
 * @param svgFiles - SVG 文件路径数组
 * @param outputPath - .ts 输出文件路径
 * @param prefix - symbol id 前缀
 */
export function generateSpriteTypes(svgFiles: string[], outputPath: string, prefix: string = 'icon-'): void {
  const iconNames = svgFiles.map((f) => `"${prefix}${path.basename(f, '.svg')}"`);

  const content = `/**
 * Auto-generated by figma-dev-tools - SVG Sprite Icon Types
 * Do not edit manually.
 */

export type IconName =
  | ${iconNames.join('\n  | ')};

/**
 * SVG Sprite 图标组件使用示例
 * 
 * 1. 在入口文件导入 sprite：
 *    import './icons/sprite.svg';
 * 
 * 2. 使用方式（React）：
 *    <svg className="icon" aria-hidden="true">
 *      <use href="#icon-name" />
 *    </svg>
 */
`;

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, content, 'utf-8');
}
