/**
 * Emotion 渲染器（v1.4.19 新增，T15）
 *
 * 设计取舍：
 * - 每个有样式的节点聚合为一个 `css({...})` 对象样式常量（emotion 序列化），
 *   节点经 css prop 引用（NodeStyleResult.extraProps → `css={cssX}`），保留原生语义标签；
 * - 相同声明签名共享同一常量；对象样式统一 camelCase 键、单引号字符串字面量；
 * - css prop 需要 @emotion/react 的 JSX 运行时（jsxImportSource 配置以 hints 给出）；
 * - React 专属：注册表框架矩阵在 Vue 侧显式拒绝。
 *
 * @module services/style-renderers/emotion-renderer
 */

import type { ProcessedNode } from '../../types/nodes.js';
import { extractCssDeclarations } from './css-modules-renderer.js';
import { collectUnsupportedFillWarnings, declarationsToObjectEntries, toPascalIdentifier } from './shared.js';
import type { NodeStyleResult, StyleHint, StylePreamble, StyleRenderer } from './types.js';

/** 注册条目：一个 css() 常量 */
interface EmotionEntry {
  /** 常量标识符（camelCase，文件内唯一） */
  readonly identifier: string;
  /** 对象样式条目 */
  readonly entries: ReturnType<typeof declarationsToObjectEntries>;
}

/** jsxImportSource 配置建议（css prop 生效前提，仅建议不写用户配置） */
const EMOTION_HINTS: readonly StyleHint[] = [
  {
    title: 'emotion jsxImportSource (required for css prop)',
    code: [
      '// Option A (recommended): tsconfig.json compilerOptions',
      '//   "jsx": "react-jsx", "jsxImportSource": "@emotion/react"',
      '// Option B: per-file pragma at the top:',
      "// /** @jsxImportSource @emotion/react */",
      "import { css } from '@emotion/react';",
    ].join('\n'),
  },
];

/**
 * Emotion 渲染器（每组件一个实例）。
 */
export class EmotionRenderer implements StyleRenderer {
  /** 样式方案标识 */
  readonly id = 'emotion' as const;
  /** 配置建议 */
  readonly hints = EMOTION_HINTS;

  /** 声明签名 → 已注册常量 */
  private readonly _bySignature = new Map<string, EmotionEntry>();
  /** 全部注册条目（输出顺序） */
  private readonly _entries: EmotionEntry[] = [];
  /** 已占用标识符 */
  private readonly _usedNames = new Set<string>();

  /**
   * 渲染单节点：注册/复用 css() 常量并以 css prop 返回。
   *
   * @param node - 精简节点
   * @param context - 渲染上下文（根节点命名）
   * @returns 节点样式结果（extraProps 携带 css prop）
   */
  renderNode(node: ProcessedNode, context?: { componentName?: string; isRoot?: boolean }): NodeStyleResult {
    const warnings = collectUnsupportedFillWarnings(node, 'Emotion');
    const declarations = extractCssDeclarations(node);
    if (declarations.length === 0) {
      return { className: '', warnings, extensionsNeeded: [] };
    }

    const signature = declarations.map(([prop, value]) => `${prop}:${value}`).join('|');
    const existing = this._bySignature.get(signature);
    if (existing) {
      return { className: '', extraProps: [`css={${existing.identifier}}`], warnings, extensionsNeeded: [] };
    }

    const pascal = toPascalIdentifier(node.name || '', 'Element');
    const baseName =
      context?.isRoot && context.componentName ? `css${context.componentName}Root` : `css${pascal}`;
    let identifier = baseName;
    let suffix = 2;
    while (this._usedNames.has(identifier)) {
      identifier = `${baseName}${suffix}`;
      suffix += 1;
    }
    this._usedNames.add(identifier);

    const entry: EmotionEntry = { identifier, entries: declarationsToObjectEntries(declarations) };
    this._bySignature.set(signature, entry);
    this._entries.push(entry);

    return { className: '', extraProps: [`css={${identifier}}`], warnings, extensionsNeeded: [] };
  }

  /**
   * 聚合输出同文件 css() 常量定义段。
   *
   * @returns 前导段（对象样式常量 + import）；无注册条目时返回 undefined
   */
  buildPreamble(): StylePreamble | undefined {
    if (this._entries.length === 0) return undefined;

    const blocks = this._entries.map((entry) => {
      const body = entry.entries.map((item) => `  ${item.key}: ${item.valueLiteral},`).join('\n');
      return `const ${entry.identifier} = css({\n${body}\n});`;
    });

    return {
      code: ['/* ============ Emotion css() styles (auto-generated by figma-dev-tools v1.4.19) ============ */', ...blocks].join(
        '\n',
      ),
      imports: ["import { css } from '@emotion/react';"],
    };
  }
}
