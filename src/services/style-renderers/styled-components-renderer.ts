/**
 * Styled Components 渲染器（v1.4.19 新增，T14）
 *
 * 设计取舍：
 * - 每个有样式的节点注册一个 `styled.<tag>` 组件，标签取自 a11y 覆盖 + 语义启发；
 *   节点在 JSX 中以该组件标识符替代原生标签（NodeStyleResult.elementIdentifier）；
 * - 相同声明签名的多个节点共享同一 styled 组件（零重复）；
 * - 全部 styled 组件经 buildPreamble 聚合在主组件声明之前同文件输出；
 * - 动态样式建议使用 transient props（$prop），ThemeProvider 用法以 hints 给出建议，
 *   渲染器不擅自创建 theme 文件；
 * - React 专属：注册表框架矩阵在 Vue 侧显式拒绝（不静默降级）。
 *
 * @module services/style-renderers/styled-components-renderer
 */

import type { ProcessedNode } from '../../types/nodes.js';
import { extractCssDeclarations } from './css-modules-renderer.js';
import { collectUnsupportedFillWarnings, nodeComponentBaseName, resolveHtmlTag } from './shared.js';
import type { NodeStyleResult, StyleHint, StylePreamble, StyleRenderer } from './types.js';

/** 注册条目：一个 styled 组件及其样式声明 */
interface StyledEntry {
  /** JSX 中使用的组件标识符（PascalCase，文件内唯一） */
  readonly identifier: string;
  /** styled.<tag> 的原生 HTML 标签 */
  readonly tag: string;
  /** 规范序 CSS 声明（直接进入模板字符串） */
  readonly declarations: ReturnType<typeof extractCssDeclarations>;
}

/** 配置/用法建议（ThemeProvider 与 transient props，仅建议不写用户项目） */
const STYLED_HINTS: readonly StyleHint[] = [
  {
    title: 'theme.ts (example)',
    code: [
      '// Optional: centralize design tokens with a Styled Components theme',
      "import { ThemeProvider } from 'styled-components';",
      '',
      'export const theme = {',
      "  colors: { primary: '#1677ff', text: '#1f2329' },",
      '  spacing: { sm: ' + "'8px'" + ', md: ' + "'16px'" + ' },',
      '};',
      '',
      '// Wrap your app: <ThemeProvider theme={theme}>...</ThemeProvider>',
      '// Inside styled templates: color: ${props => props.theme.colors.primary};',
    ].join('\n'),
  },
  {
    title: 'transient-props (guidance)',
    code: [
      '// Prefer transient props ($active) for style-only flags so they are',
      '// never forwarded to the underlying DOM node:',
      'const Item = styled.li`',
      '  color: ${(props) => (props.$active ? props.theme.colors.primary : "#646a73")};',
      '`;',
    ].join('\n'),
  },
];

/**
 * Styled Components 渲染器（每组件一个实例）。
 */
export class StyledComponentsRenderer implements StyleRenderer {
  /** 样式方案标识 */
  readonly id = 'styled' as const;
  /** 配置/用法建议 */
  readonly hints = STYLED_HINTS;

  /** 声明签名 → 已注册 styled 组件（相同样式复用） */
  private readonly _bySignature = new Map<string, StyledEntry>();
  /** 全部注册条目（输出顺序） */
  private readonly _entries: StyledEntry[] = [];
  /** 已占用标识符 */
  private readonly _usedNames = new Set<string>();

  /**
   * 渲染单节点：注册/复用 styled 组件并返回元素标识符。
   *
   * @param node - 精简节点
   * @param context - 渲染上下文（componentName/isRoot 影响根包装命名）
   * @returns 节点样式结果（elementIdentifier 驱动标签替换）
   */
  renderNode(node: ProcessedNode, context?: { componentName?: string; isRoot?: boolean }): NodeStyleResult {
    const warnings = collectUnsupportedFillWarnings(node, 'Styled Components');
    const declarations = extractCssDeclarations(node);
    if (declarations.length === 0) {
      return { className: '', warnings, extensionsNeeded: [] };
    }

    const signature = declarations.map(([prop, value]) => `${prop}:${value}`).join('|');
    const existing = this._bySignature.get(signature);
    if (existing) {
      return { className: '', elementIdentifier: existing.identifier, warnings, extensionsNeeded: [] };
    }

    const tag = resolveHtmlTag(node);
    const baseName =
      context?.isRoot && context.componentName
        ? `${context.componentName}Root`
        : nodeComponentBaseName(node, tag);
    let identifier = baseName;
    let suffix = 2;
    while (this._usedNames.has(identifier)) {
      identifier = `${baseName}${suffix}`;
      suffix += 1;
    }
    this._usedNames.add(identifier);

    const entry: StyledEntry = { identifier, tag, declarations };
    this._bySignature.set(signature, entry);
    this._entries.push(entry);

    return { className: '', elementIdentifier: identifier, warnings, extensionsNeeded: [] };
  }

  /**
   * 聚合输出同文件 styled 组件定义段。
   *
   * @returns 前导段（styled const 集合 + import）；无注册条目时返回 undefined
   */
  buildPreamble(): StylePreamble | undefined {
    if (this._entries.length === 0) return undefined;

    const blocks = this._entries.map((entry) => {
      const body = entry.declarations.map(([prop, value]) => `  ${prop}: ${value};`).join('\n');
      return `const ${entry.identifier} = styled.${entry.tag}\`\n${body}\n\`;`;
    });

    return {
      code: ['/* ============ Styled Components (auto-generated by figma-dev-tools v1.4.19) ============ */', ...blocks].join(
        '\n',
      ),
      imports: ["import styled from 'styled-components';"],
    };
  }
}
