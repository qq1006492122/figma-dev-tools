/**
 * vanilla-extract 渲染器（v1.4.19 新增，T17）
 *
 * 设计取舍：
 * - 每个有样式的节点输出一个 `style({...})` 类型安全导出，聚合于同名 `.css.ts` 旁路；
 * - React 经 `import * as styles from './X.css'` 命名空间导入，以 styles['camelName'] 访问；
 * - 相同声明签名共享导出；对象样式 camelCase 键、单引号字面量；
 * - sprinkles/recipe 的配置型能力以 hints 给出示例（sprinkles 需要全局
 *   sprinkles.css.ts 定义，超出单组件生成边界）；React 专属。
 *
 * @module services/style-renderers/vanilla-extract-renderer
 */

import type { ProcessedNode } from '../../types/nodes.js';
import { extractCssDeclarations } from './css-modules-renderer.js';
import { collectUnsupportedFillWarnings, declarationsToObjectEntries, toCamelIdentifier } from './shared.js';
import type { NodeStyleResult, StyleHint, StyleRenderer, StyleSidecarFile } from './types.js';

/** 注册条目：一个 style() 导出 */
interface VanillaEntry {
  /** 导出名（camelCase，文件内唯一） */
  readonly name: string;
  /** 对象样式条目 */
  readonly entries: ReturnType<typeof declarationsToObjectEntries>;
}

/** sprinkles/recipe 进阶用法建议 */
const VANILLA_HINTS: readonly StyleHint[] = [
  {
    title: 'sprinkles.css.ts (example, optional)',
    code: [
      "import { defineProperties, createSprinkles } from '@vanilla-extract/sprinkles';",
      '',
      '// Promote repeated Figma tokens to type-safe sprinkle properties:',
      'const layout = defineProperties({',
      "  properties: { display: ['none', 'flex', 'block'], gap: { sm: '8px', md: '16px' } },",
      '});',
      'export const sprinkles = createSprinkles(layout);',
    ].join('\n'),
  },
];

/**
 * vanilla-extract 渲染器（每组件一个实例）。
 */
export class VanillaExtractRenderer implements StyleRenderer {
  /** 样式方案标识 */
  readonly id = 'vanilla-extract' as const;
  /** styles['x'] 间接访问 + .css.ts 旁路 */
  readonly classBinding = 'css-module' as const;
  /** 进阶配置建议 */
  readonly hints = VANILLA_HINTS;

  /** 声明签名 → 已注册导出 */
  private readonly _bySignature = new Map<string, VanillaEntry>();
  /** 全部注册条目（输出顺序） */
  private readonly _entries: VanillaEntry[] = [];
  /** 已占用导出名 */
  private readonly _usedNames = new Set<string>();

  /**
   * 渲染单节点：注册/复用 style() 导出名。
   *
   * @param node - 精简节点
   * @param context - 渲染上下文（根节点命名）
   * @returns 节点样式结果（className 为导出名，经 styles['x'] 访问）
   */
  renderNode(node: ProcessedNode, context?: { componentName?: string; isRoot?: boolean }): NodeStyleResult {
    const warnings = collectUnsupportedFillWarnings(node, 'vanilla-extract');
    const declarations = extractCssDeclarations(node);
    if (declarations.length === 0) {
      return { className: '', warnings, extensionsNeeded: [] };
    }

    const signature = declarations.map(([prop, value]) => `${prop}:${value}`).join('|');
    const existing = this._bySignature.get(signature);
    if (existing) {
      return { className: existing.name, warnings, extensionsNeeded: [] };
    }

    const baseName =
      context?.isRoot && context.componentName
        ? `${context.componentName.charAt(0).toLowerCase()}${context.componentName.slice(1)}Root`
        : toCamelIdentifier(node.name || '', 'element');
    let name = baseName;
    let suffix = 2;
    while (this._usedNames.has(name)) {
      name = `${baseName}${suffix}`;
      suffix += 1;
    }
    this._usedNames.add(name);

    const entry: VanillaEntry = { name, entries: declarationsToObjectEntries(declarations) };
    this._bySignature.set(signature, entry);
    this._entries.push(entry);

    return { className: name, warnings, extensionsNeeded: [] };
  }

  /**
   * 聚合输出同名 .css.ts 旁路模块。
   *
   * @param componentName - 组件名
   * @returns 旁路文件（lang=ts，React 走命名空间导入）；无条目时 undefined
   */
  buildSidecar(componentName: string): StyleSidecarFile | undefined {
    if (this._entries.length === 0) return undefined;

    const lines: string[] = [
      `/* ${componentName}.css.ts - Auto-generated by figma-dev-tools v1.4.19 (vanilla-extract) */`,
      "import { style } from '@vanilla-extract/css';",
      '',
    ];

    for (const entry of this._entries) {
      lines.push(`export const ${entry.name} = style({`);
      for (const item of entry.entries) {
        lines.push(`  ${item.key}: ${item.valueLiteral},`);
      }
      lines.push('});');
      lines.push('');
    }

    return {
      fileName: `${componentName}.css.ts`,
      content: lines.join('\n').replace(/\n$/, ''),
      lang: 'ts',
      reactImport: `import * as styles from './${componentName}.css';`,
    };
  }
}
