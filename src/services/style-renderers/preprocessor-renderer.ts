/**
 * Less / Sass(SCSS) 预处理器渲染器（v1.4.19 新增，T16）
 *
 * 设计取舍：
 * - 与 CSS Modules 同属「语义类名 + 旁路文件」（classBinding='css-module'），
 *   React 经 styles['x']、Vue 经 $style['x'] 引用；旁路文件扩展名为 .module.less/.module.scss；
 * - 变量提取：颜色/尺寸/圆角/字体类值在全组件出现 ≥2 次时提升为 @x/$x 变量；
 * - mixin 提取：两个及以上类共享的 ≥2 条声明子集提升为 mixin（Less .x() / Sass @mixin+@include），
 *   每轮取全局最大共享子集，类只保留增量声明；
 * - 嵌套：渲染上下文携带父级类名时，子类规则嵌套输出于父规则内（后代选择器仍命中扁平化节点）；
 * - 相同声明签名共享类名（与 CSS Modules 渲染器一致）。
 *
 * @module services/style-renderers/preprocessor-renderer
 */

import type { ProcessedNode } from '../../types/nodes.js';
import {
  extractCssDeclarations,
  nodeNameToClass,
  type CssDeclaration,
} from './css-modules-renderer.js';
import { collectUnsupportedFillWarnings } from './shared.js';
import type { NodeStyleResult, StyleRenderer, StyleSidecarFile } from './types.js';

/** 预处理器方言 */
export type PreprocessorSyntax = 'less' | 'scss';

/** 注册类条目 */
interface PreprocessorClassEntry {
  /** 本地类名（kebab-case） */
  readonly name: string;
  /** 原始规范序声明（不被变量替换修改，签名/分析用） */
  readonly declarations: readonly CssDeclaration[];
  /** 父级类名（嵌套输出；缺省顶层） */
  readonly parent: string | undefined;
}

/** 变量可提升的属性 → 变量组名 */
const VARIABLE_GROUPS: Readonly<Record<string, string>> = {
  color: 'color',
  'background-color': 'color',
  gap: 'space',
  padding: 'space',
  width: 'space',
  height: 'space',
  'border-radius': 'radius',
  'font-size': 'font',
  'font-weight': 'font',
  'line-height': 'font',
};

/** 提取结果：变量表与 mixin 表 */
interface ExtractionResult {
  /** 变量名 → 值（首次出现顺序） */
  readonly variables: ReadonlyMap<string, string>;
  /** 属性:值 → 变量名（渲染替换用） */
  readonly variableByKey: ReadonlyMap<string, string>;
  /** mixin 名 → 声明列表（输出顺序） */
  readonly mixins: ReadonlyMap<string, readonly CssDeclaration[]>;
}

/**
 * Less/Sass 渲染器（每组件一个实例，两方言同构）。
 */
export class PreprocessorRenderer implements StyleRenderer {
  readonly classBinding = 'css-module' as const;
  /** 配置建议：预处理器需构建链支持（提示性，不写用户配置） */
  readonly hints = [] as const;

  /** 样式方案标识（按方言） */
  readonly id: 'less' | 'sass';

  /** 声明签名 → 已注册类（相同样式复用） */
  private readonly _bySignature = new Map<string, PreprocessorClassEntry>();
  /** 全部类条目（注册顺序） */
  private readonly _entries: PreprocessorClassEntry[] = [];
  /** 已占用类名 */
  private readonly _usedNames = new Set<string>();

  /**
   * @param syntax - less | scss
   */
  constructor(private readonly syntax: PreprocessorSyntax) {
    this.id = syntax === 'less' ? 'less' : 'sass';
  }

  /**
   * 渲染单节点：注册/复用语义类名。
   *
   * @param node - 精简节点
   * @param context - 渲染上下文（parentIdentifier 决定嵌套归属）
   * @returns 节点样式结果（className 为模块本地类名）
   */
  renderNode(
    node: ProcessedNode,
    context?: { componentName?: string; isRoot?: boolean; parentIdentifier?: string },
  ): NodeStyleResult {
    const warnings = collectUnsupportedFillWarnings(node, this.syntax === 'less' ? 'Less' : 'Sass');
    const declarations = extractCssDeclarations(node);
    if (declarations.length === 0) {
      return { className: '', warnings, extensionsNeeded: [] };
    }

    const signature = declarations.map(([prop, value]) => `${prop}:${value}`).join('|');
    const existing = this._bySignature.get(signature);
    if (existing) {
      return { className: existing.name, warnings, extensionsNeeded: [] };
    }

    const baseName = nodeNameToClass(node);
    let name = baseName;
    let suffix = 2;
    while (this._usedNames.has(name)) {
      name = `${baseName}-${suffix}`;
      suffix += 1;
    }

    const entry: PreprocessorClassEntry = {
      name,
      declarations,
      parent: context?.parentIdentifier && this._usedNames.has(context.parentIdentifier)
        ? context.parentIdentifier
        : undefined,
    };
    this._usedNames.add(name);
    this._bySignature.set(signature, entry);
    this._entries.push(entry);

    return { className: name, warnings, extensionsNeeded: [] };
  }

  /**
   * 组件树结束：提取变量/mixin 并渲染 .module.less/.module.scss 旁路文件。
   *
   * @param componentName - 组件名（文件命名）
   * @returns 旁路文件；无注册类时 undefined
   */
  buildSidecar(componentName: string): StyleSidecarFile | undefined {
    if (this._entries.length === 0) return undefined;
    const extraction = this._extractVariablesAndMixins();

    const lines: string[] = [];
    const ext = this.syntax === 'less' ? 'less' : 'scss';
    lines.push(
      `/* ${componentName}.module.${ext} - Auto-generated by figma-dev-tools v1.4.19 (${this.syntax === 'less' ? 'Less' : 'Sass/SCSS'}) */`,
    );

    // ============ 变量 ============
    if (extraction.variables.size > 0) {
      lines.push('');
      lines.push('// ============ Variables ============');
      for (const [name, value] of extraction.variables) {
        lines.push(`${this._varRef(name)}: ${value};`);
      }
    }

    // ============ Mixins ============
    if (extraction.mixins.size > 0) {
      lines.push('');
      lines.push('// ============ Mixins ============');
      for (const [name, declarations] of extraction.mixins) {
        if (this.syntax === 'less') {
          lines.push(`.${name}() {`);
        } else {
          lines.push(`@mixin ${name} {`);
        }
        for (const [prop, value] of declarations) {
          lines.push(`  ${prop}: ${this._resolveValue(prop, value, extraction.variableByKey)};`);
        }
        lines.push(this.syntax === 'less' ? '}' : '}');
      }
    }

    // ============ 类规则（嵌套树） ============
    lines.push('');
    lines.push('// ============ Component classes ============');
    const childrenByParent = new Map<string, PreprocessorClassEntry[]>();
    const roots: PreprocessorClassEntry[] = [];
    for (const entry of this._entries) {
      if (entry.parent && this._byName(entry.parent)) {
        const list = childrenByParent.get(entry.parent) ?? [];
        list.push(entry);
        childrenByParent.set(entry.parent, list);
      } else {
        roots.push(entry);
      }
    }

    /** 每个类被哪些 mixin 命中（构建期一次性计算） */
    const mixinsOf = this._assignMixins(extraction.mixins);

    const emitClass = (entry: PreprocessorClassEntry, indent: string): void => {
      const mixinNames = mixinsOf.get(entry.name) ?? [];
      const mixinKeySet = new Set<string>();
      for (const name of mixinNames) {
        for (const [prop, value] of extraction.mixins.get(name) ?? []) {
          mixinKeySet.add(`${prop}:${value}`);
        }
      }
      const ownDeclarations = entry.declarations.filter(([prop, value]) => !mixinKeySet.has(`${prop}:${value}`));
      const children = childrenByParent.get(entry.name) ?? [];

      lines.push(`${indent}.${entry.name} {`);
      for (const name of mixinNames) {
        lines.push(`${indent}  ${this._mixinInclude(name)}`);
      }
      for (const [prop, value] of ownDeclarations) {
        lines.push(`${indent}  ${prop}: ${this._resolveValue(prop, value, extraction.variableByKey)};`);
      }
      for (const child of children) {
        emitClass(child, `${indent}  `);
      }
      lines.push(`${indent}}`);
    };

    for (const root of roots) {
      emitClass(root, '');
      lines.push('');
    }

    return {
      fileName: `${componentName}.module.${ext}`,
      content: lines.join('\n'),
      lang: this.syntax === 'less' ? 'less' : 'scss',
    };
  }

  // ============ 内部分析 ============

  /** 按名取条目 */
  private _byName(name: string): PreprocessorClassEntry | undefined {
    return this._entries.find((entry) => entry.name === name);
  }

  /** 变量引用字面量（@x / $x） */
  private _varRef(name: string): string {
    return this.syntax === 'less' ? `@${name}` : `$${name}`;
  }

  /** mixin 调用语句 */
  private _mixinInclude(name: string): string {
    return this.syntax === 'less' ? `.${name}();` : `@include ${name};`;
  }

  /** 声明值变量替换（无可提升变量时原值输出） */
  private _resolveValue(prop: string, value: string, variableByKey: ReadonlyMap<string, string>): string {
    return variableByKey.get(`${prop}:${value}`)
      ? this._varRef(variableByKey.get(`${prop}:${value}`) as string)
      : value;
  }

  /**
   * 提取变量：可提升属性的值在全组件（含各类原始声明）出现 ≥2 次即提升，
   * 变量按首次出现顺序、组内编号命名（@color-1 / $space-2）。
   */
  private _extractVariablesAndMixins(): ExtractionResult {
    // ---- 变量 ----
    const occurrence = new Map<string, { group: string; value: string; firstIndex: number }>();
    let scanIndex = 0;
    for (const entry of this._entries) {
      for (const [prop, value] of entry.declarations) {
        const group = VARIABLE_GROUPS[prop];
        if (!group) continue;
        const key = `${prop}:${value}`;
        if (!occurrence.has(key)) {
          occurrence.set(key, { group, value, firstIndex: scanIndex++ });
        }
      }
    }

    const variables = new Map<string, string>();
    const variableByKey = new Map<string, string>();
    /** 组 → 下一个编号 */
    const groupCounters = new Map<string, number>();
    /** (组,值) → 变量名（同值不同属性也应共享：按 组+值 命名） */
    const varNameByGroupValue = new Map<string, string>();

    // 统计每个 组:值 的键出现次数（不同属性也算同值复用）
    const groupValueKeys = new Map<string, Set<string>>();
    for (const [key, meta] of occurrence) {
      const gv = `${meta.group}|${meta.value}`;
      const keys = groupValueKeys.get(gv) ?? new Set<string>();
      keys.add(key);
      groupValueKeys.set(gv, keys);
    }

    // 仅当同组同值覆盖 ≥2 个声明键（即在 ≥2 处出现）时提升
    const eligible = Array.from(occurrence.entries())
      .filter(([, meta]) => (groupValueKeys.get(`${meta.group}|${meta.value}`)?.size ?? 0) >= 2)
      .sort((a, b) => a[1].firstIndex - b[1].firstIndex);

    for (const [key, meta] of eligible) {
      const gv = `${meta.group}|${meta.value}`;
      let name = varNameByGroupValue.get(gv);
      if (!name) {
        const next = (groupCounters.get(meta.group) ?? 0) + 1;
        groupCounters.set(meta.group, next);
        name = `${meta.group}-${next}`;
        varNameByGroupValue.set(gv, name);
        variables.set(name, meta.value);
      }
      variableByKey.set(key, name);
    }

    // ---- Mixins：迭代选取全局最大共享子集 ----
    const mixins = new Map<string, readonly CssDeclaration[]>();
    /** 类名 → 剩余声明键集（分析副本） */
    const remaining = new Map<string, Set<string>>();
    const declByKey = new Map<string, CssDeclaration>();
    for (const entry of this._entries) {
      const keys = new Set(entry.declarations.map(([prop, value]) => `${prop}:${value}`));
      remaining.set(entry.name, keys);
      for (const decl of entry.declarations) {
        declByKey.set(`${decl[0]}:${decl[1]}`, decl);
      }
    }

    let mixinIndex = 1;
    for (;;) {
      let best: { keys: string[]; classes: string[] } | undefined;
      const names = this._entries.map((entry) => entry.name);
      for (let i = 0; i < names.length; i++) {
        for (let j = i + 1; j < names.length; j++) {
          const a = remaining.get(names[i] as string) as Set<string>;
          const b = remaining.get(names[j] as string) as Set<string>;
          const intersection: string[] = [];
          for (const key of a) {
            if (b.has(key)) intersection.push(key);
          }
          if (intersection.length >= 2 && (!best || intersection.length > best.keys.length)) {
            // 收集全部含该子集的类
            const classes = names.filter((name) => {
              const set = remaining.get(name) as Set<string>;
              return intersection.every((key) => set.has(key));
            });
            best = { keys: intersection, classes };
          }
        }
      }
      if (!best) break;

      const mixinName = `mixin-${mixinIndex++}`;
      const declarations = best.keys
        .map((key) => declByKey.get(key))
        .filter((decl): decl is CssDeclaration => decl !== undefined);
      mixins.set(mixinName, declarations);
      for (const className of best.classes) {
        const set = remaining.get(className) as Set<string>;
        for (const key of best.keys) set.delete(key);
      }
    }

    return { variables, variableByKey, mixins };
  }

  /**
   * 计算每个类命中的 mixin 列表（基于原始声明包含关系；mixin 间可能重叠，按定义序输出）。
   */
  private _assignMixins(mixins: ReadonlyMap<string, readonly CssDeclaration[]>): Map<string, string[]> {
    const result = new Map<string, string[]>();
    for (const entry of this._entries) {
      const ownKeys = new Set(entry.declarations.map(([prop, value]) => `${prop}:${value}`));
      const hit: string[] = [];
      for (const [name, declarations] of mixins) {
        if (declarations.every(([prop, value]) => ownKeys.has(`${prop}:${value}`))) {
          hit.push(name);
        }
      }
      if (hit.length > 0) result.set(entry.name, hit);
    }
    return result;
  }
}
