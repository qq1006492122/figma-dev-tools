/**
 * Panda CSS 渲染器（v1.4.19 新增，T17）
 *
 * 设计取舍：
 * - 每个有样式的节点聚合为 `css({...})` 字符串常量（Panda 返回原子类名字符串），
 *   节点经 className 表达式引用（classNameIsExpression=true）；
 * - 相同声明签名共享常量；对象样式 camelCase 键、单引号字面量；
 * - cva/recipe 的变体模式以 hints 给出示例（需要显式 variants 配置，
 *   单节点静态样式不臆造变体）；React 专属；import 路径默认 @/styled-system/css，
 *   需与 Panda outdir/tsconfig paths 对齐（hints 说明）。
 *
 * @module services/style-renderers/panda-renderer
 */

import type { ProcessedNode } from '../../types/nodes.js';
import { extractCssDeclarations } from './css-modules-renderer.js';
import { collectUnsupportedFillWarnings, declarationsToObjectEntries, toCamelIdentifier } from './shared.js';
import type { NodeStyleResult, StyleHint, StylePreamble, StyleRenderer } from './types.js';

/** 注册条目：一个 css() 常量 */
interface PandaEntry {
  /** 常量名（camelCase，文件内唯一） */
  readonly name: string;
  /** 对象样式条目 */
  readonly entries: ReturnType<typeof declarationsToObjectEntries>;
}

/** cva/recipe 与 outdir 路径建议 */
const PANDA_HINTS: readonly StyleHint[] = [
  {
    title: 'panda cva/recipe (example for variants)',
    code: [
      "import { cva } from '@/styled-system/css';",
      '',
      '// Use cva when Figma component properties define visual variants:',
      'const button = cva({',
      "  base: { display: 'inline-flex', borderRadius: '8px' },",
      "  variants: { variant: { primary: { background: '#1677ff' }, ghost: { background: 'transparent' } } },",
      '});',
    ].join('\n'),
  },
  {
    title: 'panda outdir import path',
    code: [
      '// Generated constants import from the Panda outdir (default: <root>/styled-system).',
      "// This generator emits '@/styled-system/css'; adjust the path or your",
      '// tsconfig `paths` / panda.config outdir if your setup differs.',
    ].join('\n'),
  },
];

/**
 * Panda CSS 渲染器（每组件一个实例）。
 */
export class PandaRenderer implements StyleRenderer {
  /** 样式方案标识 */
  readonly id = 'panda' as const;
  /** 配置/用法建议 */
  readonly hints = PANDA_HINTS;

  /** 声明签名 → 已注册常量 */
  private readonly _bySignature = new Map<string, PandaEntry>();
  /** 全部注册条目（输出顺序） */
  private readonly _entries: PandaEntry[] = [];
  /** 已占用常量名 */
  private readonly _usedNames = new Set<string>();

  /**
   * 渲染单节点：注册/复用 css() 常量，返回 className 表达式引用。
   *
   * @param node - 精简节点
   * @param context - 渲染上下文（根节点命名）
   * @returns 节点样式结果（className 为常量标识符，按表达式输出）
   */
  renderNode(node: ProcessedNode, context?: { componentName?: string; isRoot?: boolean }): NodeStyleResult {
    const warnings = collectUnsupportedFillWarnings(node, 'Panda CSS');
    const declarations = extractCssDeclarations(node);
    if (declarations.length === 0) {
      return { className: '', warnings, extensionsNeeded: [] };
    }

    const signature = declarations.map(([prop, value]) => `${prop}:${value}`).join('|');
    const existing = this._bySignature.get(signature);
    if (existing) {
      return {
        className: existing.name,
        classNameIsExpression: true,
        warnings,
        extensionsNeeded: [],
      };
    }

    const baseName =
      context?.isRoot && context.componentName
        ? `${context.componentName.charAt(0).toLowerCase()}${context.componentName.slice(1)}Root`
        : toCamelIdentifier(node.name || '', 'element');
    let name = baseName;
    let suffix = 2;
    while (this._usedNames.has(name)) {
      name = `${baseName}${suffix}`;
      suffix += 1;
    }
    this._usedNames.add(name);

    const entry: PandaEntry = { name, entries: declarationsToObjectEntries(declarations) };
    this._bySignature.set(signature, entry);
    this._entries.push(entry);

    return { className: name, classNameIsExpression: true, warnings, extensionsNeeded: [] };
  }

  /**
   * 聚合输出同文件 css() 常量定义段。
   *
   * @returns 前导段（常量集合 + outdir import）；无注册条目时 undefined
   */
  buildPreamble(): StylePreamble | undefined {
    if (this._entries.length === 0) return undefined;

    const blocks = this._entries.map((entry) => {
      const body = entry.entries.map((item) => `  ${item.key}: ${item.valueLiteral},`).join('\n');
      return `const ${entry.name} = css({\n${body}\n});`;
    });

    return {
      code: ['/* ============ Panda CSS css() styles (auto-generated by figma-dev-tools v1.4.19) ============ */', ...blocks].join(
        '\n',
      ),
      imports: ["import { css } from '@/styled-system/css';"],
    };
  }
}
