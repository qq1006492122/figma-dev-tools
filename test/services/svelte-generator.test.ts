/**
 * SvelteGenerator 单元测试（WBS-P1-11 / P1-12）
 *
 * 口径：Svelte 4 默认（<script lang="ts"> + export let props + on:event），
 * Svelte 5 runes 仅在注释中建议；样式仅承诺 tailwind / unocss / css-modules，
 * 其中 css-modules 实际输出 Svelte scoped <style>，不承诺 hash/composes 语义。
 */
import { describe, it, expect, vi, beforeEach } from 'vitest';
import { SvelteGenerator, createSvelteGenerator } from '../../src/services/svelte-generator.js';
import { UnsupportedStyleFormatError } from '../../src/services/style-renderers/registry.js';
import type { DesignContext, ProcessedNode } from '../../src/types/nodes.js';

const mockFigmaClient = {
  getFile: vi.fn(),
  getNode: vi.fn(),
  getImage: vi.fn(),
  getSvg: vi.fn(),
  getImages: vi.fn(),
  downloadImage: vi.fn(),
} as any;

function ctx(node: Partial<ProcessedNode>): DesignContext {
  return {
    fileKey: 'f',
    nodeId: '1:1',
    node: {
      id: '1', figmaId: '1:1', name: 'Card', originalType: 'FRAME', role: 'container',
      visible: true, clipsContent: false, size: { width: 320, height: 120 }, children: [],
      ...node,
    } as ProcessedNode,
    componentsUsed: [],
    styles: [],
    warnings: [],
    metadata: { name: 'Card', lastModified: '' },
  };
}

const box = (id: string, partial: Partial<ProcessedNode> = {}): ProcessedNode =>
  ({
    id, figmaId: id, name: id, originalType: 'FRAME', role: 'container', visible: true,
    clipsContent: false, size: { width: 100, height: 40 }, children: [], ...partial,
  }) as ProcessedNode;

describe('WBS-P1-11 Svelte 生成器核心', () => {
  let gen: SvelteGenerator;
  beforeEach(() => {
    gen = new SvelteGenerator(mockFigmaClient);
    vi.clearAllMocks();
  });

  it('工厂函数返回 SvelteGenerator 实例', () => {
    expect(createSvelteGenerator(mockFigmaClient)).toBeInstanceOf(SvelteGenerator);
  });

  it('容器节点：<script lang="ts"> + 模板 + 占位 <style>，默认 Svelte 4 口径', async () => {
    const r = await gen.generateFromContext(ctx({}), { componentName: 'HelloCard' });
    expect(r.svelteVersion).toBe(4);
    expect(r.code).toContain('<script lang="ts">');
    expect(r.code).toMatch(/<(div|section)[\s>]/);
    expect(r.code).toContain('<style');
    expect(r.code).toContain('Generated by figma-dev-tools');
    // Svelte 5 runes 仅作注释建议，不默认输出
    expect(r.code).toMatch(/Svelte 5|runes/);
  });

  it('文本节点：安全转义后输出为元素文本（无 JSX 式 dangerouslySetInnerHTML）', async () => {
    const r = await gen.generateFromContext(
      ctx({
        originalType: 'TEXT',
        role: 'text',
        textContent: '你好 <世界> & 朋友',
      }),
      { componentName: 'Greet' },
    );
    expect(r.code).toContain('你好 &lt;世界&gt; &amp; 朋友');
  });

  it('不可见节点默认不输出，结构与 Vue/Weapp 剪枝口径一致', async () => {
    const r = await gen.generateFromContext(
      ctx({ children: [box('a'), box('b', { visible: false })] }),
      { componentName: 'VisibleOnly' },
    );
    // 根 section + 仅一个子 div
    const opens = r.code.match(/<(div|section)[\s>]/g) ?? [];
    expect(opens).toHaveLength(2);
  });

  it('Component Properties → export let props（TS 类型 + 默认值；VARIANT 给联合字面量）', async () => {
    const r = await gen.generateFromContext(
      ctx({
        componentProperties: [
          { name: 'Title', propName: 'title', type: 'TEXT', required: false, defaultValue: '标题' },
          { name: 'Disabled', propName: 'disabled', type: 'BOOLEAN', required: false, defaultValue: false },
          { name: 'Variant', propName: 'variant', type: 'VARIANT', required: true, variantOptions: ['primary', 'ghost'] },
          { name: 'Count', propName: 'count', type: 'TEXT', required: false, defaultValue: '3' },
        ],
      }),
      { componentName: 'PropCard' },
    );
    const script = r.code;
    expect(script).toContain("export let title: string = '标题';");
    expect(script).toContain('export let disabled: boolean = false;');
    expect(script).toContain("export let variant: 'primary' | 'ghost';");
    // 数字形态默认值：保字符串默认，标注 TODO（不臆造数字解析）
    expect(script).toMatch(/count/);
  });

  it('非 TS 模式：export let 无类型注解，createEventDispatcher 同样可用', async () => {
    const r = await gen.generateFromContext(
      ctx({
        componentProperties: [
          { name: 'Title', propName: 'title', type: 'TEXT', required: false, defaultValue: 'x' },
        ],
      }),
      { componentName: 'JsCard', typescript: false },
    );
    expect(r.code).toContain('<script>');
    expect(r.code).not.toContain('<script lang="ts">');
    expect(r.code).toContain("export let title = 'x';");
  });

  it('按钮：on:click 绑定 + createEventDispatcher + 处理函数骨架', async () => {
    const r = await gen.generateFromContext(
      ctx({
        name: 'Submit Button',
        role: 'button',
        children: [
          {
            id: 'lbl', figmaId: 'lbl', name: 'Label', originalType: 'TEXT', role: 'text', visible: true,
            textContent: '提交', size: { width: 40, height: 20 }, clipsContent: false, children: [],
          } as ProcessedNode,
        ],
      }),
      { componentName: 'SubmitForm' },
    );
    expect(r.code).toMatch(/on:click=\{onSubmitButtonClick\}/);
    expect(r.code).toContain("import { createEventDispatcher } from 'svelte';");
    expect(r.code).toContain('const dispatch = createEventDispatcher();');
    expect(r.code).toMatch(/const onSubmitButtonClick = \(\) => \{[\s\S]*?dispatch\('click'\)/);
    expect(r.events).toContainEqual({ event: 'click', handler: 'onSubmitButtonClick', tag: 'button' });
    expect(r.code).toContain('提交');
  });

  it('输入框：on:input 读取 event.currentTarget.value 并 dispatch', async () => {
    const r = await gen.generateFromContext(
      ctx({ name: 'Name Input', role: 'input', size: { width: 200, height: 40 } }),
      { componentName: 'NameField' },
    );
    expect(r.code).toMatch(/on:input=\{onNameInputInput\}/);
    expect(r.code).toContain('event.currentTarget.value');
    expect(r.code).toMatch(/dispatch\('input'/);
  });

  it('表单：on:submit|preventDefault 阻止原生提交', async () => {
    const r = await gen.generateFromContext(
      ctx({ name: 'Login Form', size: { width: 320, height: 200 } }),
      { componentName: 'LoginPanel' },
    );
    expect(r.code).toContain('on:submit|preventDefault={onLoginFormSubmit}');
    expect(r.code).toMatch(/<form[\s>]/);
  });

  it('同名节点 handler 全局唯一（数字后缀去重）', async () => {
    const r = await gen.generateFromContext(
      ctx({
        children: [
          box('ok1', { name: 'Ok Button', role: 'button', size: { width: 80, height: 36 } }),
          box('ok2', { name: 'Ok Button', role: 'button', size: { width: 80, height: 36 } }),
        ],
      }),
      { componentName: 'DupHandlers' },
    );
    expect(r.code).toContain('onOkButtonClick');
    expect(r.code).toContain('onOkButtonClick2');
    const handlers = r.events.filter((e) => e.event === 'click');
    expect(new Set(handlers.map((h) => h.handler)).size).toBe(2);
  });
});

describe('WBS-P1-11 列表 {#each} 与条件 {#if}', () => {
  let gen: SvelteGenerator;
  beforeEach(() => {
    gen = new SvelteGenerator(mockFigmaClient);
    vi.clearAllMocks();
  });

  function row(id: string, textValue: string): ProcessedNode {
    return box(id, {
      name: 'Message Row',
      size: { width: 300, height: 56 },
      children: [
        {
          id: `${id}-t`, figmaId: `${id}-t`, name: 'Name Text', originalType: 'TEXT', role: 'text', visible: true,
          textContent: textValue, size: { width: 200, height: 20 }, clipsContent: false, children: [],
        } as ProcessedNode,
      ],
    });
  }

  it('3 个同名同构子节点 → {#each} 只渲染原型，文本插值 {item.field}，脚本导出占位数组', async () => {
    const r = await gen.generateFromContext(
      ctx({ children: [row('r1', '张三'), row('r2', '李四'), row('r3', '王五')] }),
      { componentName: 'MessageList' },
    );
    // each 块：语义化 dataKey/别名由推断器决定，这里锁语法结构（keyed each）
    expect(r.code).toMatch(/\{#each\s+\w+\s+as\s+\w+,\s*\w+\s*\(\w+\.id\)\}/);
    expect(r.code).toContain('{/each}');
    // 模板区只渲染原型（张三），折叠成员文案仅出现在脚本占位数组中
    const markupOnly = r.code.split('<script')[0];
    expect(markupOnly).not.toContain('李四');
    expect(markupOnly).not.toContain('王五');
    expect(r.code).toMatch(/\{\w+\.\w+\}/);
    // 脚本导出可直接运行的占位数据（含 id 字段）
    expect(r.code).toMatch(/export let \w+: Array<\{[\s\S]*?id: string[\s\S]*?\}>\s*=\s*\[/);
    expect(r.code).toContain("id: 'item-0'");
  });

  it('inference.list=false 关闭推断 → 静态渲染全部子节点', async () => {
    const r = await gen.generateFromContext(
      ctx({ children: [row('s1', '甲'), row('s2', '乙'), row('s3', '丙')] }),
      { componentName: 'StaticRows', inference: { list: false } },
    );
    expect(r.code).not.toContain('{#each ');
    expect(r.code).toContain('甲');
    expect(r.code).toContain('乙');
    expect(r.code).toContain('丙');
  });

  it('显式条件：同父兄弟形成 {#if}/{:else if}/{:else} 链', async () => {
    const r = await gen.generateFromContext(
      ctx({
        children: [
          box('tab-a', { name: 'Tab A Panel' }),
          box('tab-b', { name: 'Tab B Panel' }),
          box('tab-c', { name: 'Tab C Panel' }),
        ],
      }),
      {
        componentName: 'CondPanels',
        conditions: [
          { nodeId: 'tab-a', groupId: 'g1', expression: 'active === "a"' },
          { nodeId: 'tab-b', groupId: 'g1', expression: 'active === "b"' },
          { nodeId: 'tab-c', groupId: 'g1', isElse: true },
        ],
      },
    );
    expect(r.code).toContain('{#if active === "a"}');
    expect(r.code).toContain('{:else if active === "b"}');
    expect(r.code).toContain('{:else}');
    expect(r.code).toContain('{/if}');
  });

  it('directive=hidden：输出 hidden 属性表达式而非 {#if} 块', async () => {
    const r = await gen.generateFromContext(
      ctx({ children: [box('tip', { name: 'Tooltip Bubble' })] }),
      {
        componentName: 'HideTip',
        conditions: [{ nodeId: 'tip', expression: 'showTip', directive: 'hidden' }],
      },
    );
    expect(r.code).not.toContain('{#if');
    expect(r.code).toContain('hidden={showTip}');
  });

  it('默认不开名称信号条件：仅返回 conditionSuggestions，不自动生成 {#if}', async () => {
    const r = await gen.generateFromContext(
      ctx({ children: [box('modal', { name: 'Modal Dialog', visible: false })] }),
      { componentName: 'SuggestOnly' },
    );
    expect(r.code).not.toContain('{#if');
    expect(r.conditionSuggestions.length).toBeGreaterThan(0);
  });
});

describe('WBS-P1-12 样式三组合与非法组合', () => {
  let gen: SvelteGenerator;
  beforeEach(() => {
    gen = new SvelteGenerator(mockFigmaClient);
    vi.clearAllMocks();
  });

  const radius = { topLeft: 6, topRight: 6, bottomRight: 6, bottomLeft: 6, uniform: true };
  const styledNode = (): Partial<ProcessedNode> => ({
    layout: {
      mode: 'HORIZONTAL', primaryAxisAlign: 'CENTER', counterAxisAlign: 'CENTER',
      primaryAxisSizing: 'FIXED', counterAxisSizing: 'FIXED', layoutWrap: 'NO_WRAP',
      itemSpacing: 8, padding: { top: 8, right: 8, bottom: 8, left: 8 },
    } as ProcessedNode['layout'],
    fills: [{ type: 'solid', color: { r: 0.2, g: 0.4, b: 0.8, a: 1 }, opacity: 1 }] as ProcessedNode['fills'],
    cornerRadius: radius,
  });

  it('tailwind（默认）：原子类进 class，scoped 占位 style，不产出旁路文件', async () => {
    const r = await gen.generateFromContext(ctx(styledNode()), {
      componentName: 'TailwindCard',
      styleFormat: 'tailwind',
    });
    expect(r.code).toMatch(/class="[^"]*(flex|items-center|justify-center)[^"]*"/);
    expect(r.code).toContain('<style');
    expect(r.styleSidecar).toBeUndefined();
  });

  it('unocss attributify：安全 token 提升为无值属性', async () => {
    const r = await gen.generateFromContext(ctx(styledNode()), {
      componentName: 'UnoCard',
      styleFormat: 'unocss',
      unocssMode: 'attributify',
    });
    expect(r.code).toMatch(/flex=""/);
    expect(r.styleHints.length).toBeGreaterThan(0);
  });

  it('css-modules：语义类名 + 内联 scoped <style>（composes 已展开，不输出 .module 旁路）', async () => {
    const r = await gen.generateFromContext(
      ctx({
        ...styledNode(),
        children: [
          box('inner', {
            name: 'Inner Box',
            size: { width: 40, height: 24 },
            fills: [{ type: 'solid', color: { r: 0.2, g: 0.4, b: 0.8, a: 1 }, opacity: 1 }] as ProcessedNode['fills'],
            cornerRadius: { ...radius },
            // 声明为外层子集（少一条布局声明），渲染器可能产出 composes
            layout: {
              mode: 'HORIZONTAL', primaryAxisAlign: 'CENTER', counterAxisAlign: 'CENTER',
              primaryAxisSizing: 'FIXED', counterAxisSizing: 'FIXED', layoutWrap: 'NO_WRAP',
              itemSpacing: 8, padding: { top: 8, right: 8, bottom: 8, left: 8 },
            } as ProcessedNode['layout'],
          }),
        ],
      }),
      { componentName: 'ModuleCard', styleFormat: 'css-modules' },
    );
    // 语义 kebab 类名静态绑定（无 styles[ ] / $style）
    expect(r.code).toMatch(/class="[a-z0-9-]+"/);
    expect(r.code).not.toContain('styles[');
    expect(r.code).not.toContain('$style');
    // 样式内联在 SFC 的 scoped style 中
    expect(r.code).toMatch(/<style>\s*\/\*[\s\S]*?flex[\s\S]*?<\/style>/);
    expect(r.code).toContain('border-radius');
    // composes 不出现在最终产物（已被展开合并）
    expect(r.code).not.toContain('composes:');
    // 明确写明非 hash/composes 语义
    expect(r.code).toMatch(/不承诺\s*CSS Modules|scoped/);
    expect(r.styleSidecar).toBeUndefined();
  });

  it.each(['styled', 'emotion', 'vanilla-extract', 'panda', 'less', 'sass', 'inline-styles'] as const)(
    '非法组合 %s 在任何网络请求前抛 UnsupportedStyleFormatError',
    async (fmt) => {
      await expect(
        gen.generateFromContext(ctx(styledNode()), { componentName: 'BadCombo', styleFormat: fmt as any }),
      ).rejects.toBeInstanceOf(UnsupportedStyleFormatError);
      expect(mockFigmaClient.getFile).not.toHaveBeenCalled();
    },
  );
});
